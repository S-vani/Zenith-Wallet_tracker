// Generates the spring easings in src/design/springs.css as CSS linear() curves, from real damped-spring physics
// (so they are springs, not guessed Bezier curves). Run: node scripts/gen-springs.mjs
import {writeFileSync} from "node:fs";

// step response of a damped spring from 0 to 1: stiffness k, damping ratio z (z < 1 overshoots)
function spring(z, omega, t) {
    if (z >= 1) return 1 - Math.exp(-omega * t) * (1 + omega * t);
    const wd = omega * Math.sqrt(1 - z * z);
    return 1 - Math.exp(-z * omega * t) * (Math.cos(wd * t) + (z * omega / wd) * Math.sin(wd * t));
}

// samples until the motion has settled, returning the linear() string and the duration in ms
function curve(z, omega) {
    const points = [];
    let settledAt = 0;
    for (let t = 0; t <= 3; t += 0.004) {
        const v = spring(z, omega, t);
        points.push([t, v]);
        if (Math.abs(1 - v) > 0.002) settledAt = t;
    }
    const duration = Math.min(3, settledAt + 0.02);
    const count = 34;
    const out = [];
    for (let i = 0; i <= count; i++) {
        const t = (i / count) * duration;
        out.push(i === count ? 1 : Number(spring(z, omega, t).toFixed(4)));
    }
    return {easing: `linear(${out.join(", ")})`, ms: Math.round(duration * 1000)};
}

const springs = {
    soft: curve(0.82, 11),    // a gentle settle, little overshoot (sheets, cards)
    snappy: curve(0.7, 18),   // quick with a small overshoot (toggles, chips)
    bouncy: curve(0.5, 14),   // visible bounce (the milestone pop, rare)
};
let css = "/* GENERATED by scripts/gen-springs.mjs: spring easings as CSS linear() curves. Do not edit by hand. */\n:root {\n";
for (const [name, {easing, ms}] of Object.entries(springs)) {
    css += `    --spring-${name}: ${easing};\n    --spring-${name}-ms: ${ms}ms; /* the time it takes to settle */\n`;
}
css += "}\n";
writeFileSync(new URL("../src/design/springs.css", import.meta.url), css);
